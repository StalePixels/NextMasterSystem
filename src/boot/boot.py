#!/usr/bin/env python3
"""Build helper for the maze cart (boot.asm).

  boot.py tiles OUT.inc   write the tile graphics as sjasmplus db lines
  boot.py header CART     write the checksum into the cart's header at $7FF0

Tile numbers (boot.asm uses the same):
  0       floor
  1-16    hedge wall, 1 + a mask of the wall neighbours (N 1, E 2, S 4, W 8)
  17      exit
  18-21   player: facing right standing, right walking, left standing, left walking
"""
import sys

# Background colour numbers (palette in boot.asm).
FLOOR, DOT, DARK, MID, LIGHT, LEAF, EXIT_Y, EXIT_W, EXIT_O = range(9)


def floor():
    t = [[FLOOR] * 8 for _ in range(8)]
    t[2][5] = DOT
    t[6][1] = DOT
    return t


def wall(mask):
    """A hedge block: a centre square with an arm to each wall neighbour."""
    n, e, s, w = (mask & 1, mask & 2, mask & 4, mask & 8)

    def solid(x, y):
        if not (0 <= x < 8 and 0 <= y < 8):
            # outside the tile: solid where an arm leaves through that edge
            if y < 0:
                return bool(n) and 1 <= x <= 6
            if y > 7:
                return bool(s) and 1 <= x <= 6
            if x < 0:
                return bool(w) and 1 <= y <= 6
            return bool(e) and 1 <= y <= 6
        if 1 <= x <= 6 and 1 <= y <= 6:
            return True
        if n and y <= 1 and 1 <= x <= 6:
            return True
        if s and y >= 6 and 1 <= x <= 6:
            return True
        if w and x <= 1 and 1 <= y <= 6:
            return True
        if e and x >= 6 and 1 <= y <= 6:
            return True
        return False

    t = [[FLOOR] * 8 for _ in range(8)]
    for y in range(8):
        for x in range(8):
            if not solid(x, y):
                continue
            if not solid(x, y + 1) or not solid(x + 1, y):
                c = DARK          # shadow on the lower and right edges
            elif not solid(x, y - 1) or not solid(x - 1, y):
                c = LIGHT         # light on the upper and left edges
            else:
                c = LEAF if (x * 3 + y * 5) % 7 == 0 else MID
            t[y][x] = c
    return t


def exit_tile():
    t = floor()
    for y in range(8):
        for x in range(8):
            d = abs(x - 3.5) + abs(y - 3.5)
            if d <= 1:
                t[y][x] = EXIT_W
            elif d <= 2:
                t[y][x] = EXIT_Y
            elif d <= 3:
                t[y][x] = EXIT_O
    return t


# The player, facing right: all dark blue (1), no arms; the eye is a gap.
PLAYER = {
    'stand': [
        '...1111.',
        '..111111',
        '.1111.11',
        '11.11111',
        '1...111.',
        '....111.',
        '....1.1.',
        '....1.1.',
    ],
    'walk': [
        '...1111.',
        '..111111',
        '.1111.11',
        '11.11111',
        '1...111.',
        '....111.',
        '...1..1.',
        '..1....1',
    ],
}


def sprite(rows, mirror):
    t = []
    for r in rows:
        if mirror:
            r = r[::-1]
        t.append([0 if c == '.' else int(c) for c in r])
    return t


def planar(t):
    """8x8 colour numbers -> 32 bytes of Master System tile data."""
    out = []
    for row in t:
        for p in range(4):
            b = 0
            for x in range(8):
                if row[x] >> p & 1:
                    b |= 0x80 >> x
            out.append(b)
    return out


def tiles(path):
    ts = [floor()] + [wall(m) for m in range(16)] + [exit_tile()]
    ts += [sprite(PLAYER['stand'], False), sprite(PLAYER['walk'], False),
           sprite(PLAYER['stand'], True), sprite(PLAYER['walk'], True)]
    with open(path, 'w') as f:
        f.write('; generated by boot.py, do not edit\n')
        for t in ts:
            f.write('    db ' + ','.join(f'${b:02X}' for b in planar(t)) + '\n')


def header(path):
    rom = bytearray(open(path, 'rb').read())
    if len(rom) != 0x8000 or rom[0x7FF0:0x7FF8] != b'TMR SEGA':
        sys.exit(f'{path}: not a 32K cart with a TMR SEGA header')
    s = sum(rom[:0x7FF0]) & 0xFFFF
    rom[0x7FFA] = s & 0xFF
    rom[0x7FFB] = s >> 8
    open(path, 'wb').write(rom)


if __name__ == '__main__':
    if len(sys.argv) != 3 or sys.argv[1] not in ('tiles', 'header'):
        sys.exit(__doc__)
    {'tiles': tiles, 'header': header}[sys.argv[1]](sys.argv[2])
