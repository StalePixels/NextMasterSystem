#!/usr/bin/env python3
"""Write the lookup tables for the NextMasterSystem framework.

usage: gentables.py TABLES.INC TABLES2.INC TABLES3.INC

TABLES.INC (resident page, MMU7):
  mapattr[h]: SMS name table high byte -> Next tilemap attribute byte.
  pal_hi/lo[c]: SMS colour --BBGGRR -> NextReg $44 first and second byte.
  joy_table[k]: port $1F bits (0 R,1 L,2 D,3 U,4 B,5 C) -> SMS port $DC bits.
  ay_vol[a]: SN76489 attenuation (0 loudest, 15 off, 2 dB steps) -> AY volume.
TABLES2.INC (second framework page):
  conv_k[b] (k = 0..3): SMS bitplane byte b -> Next packed byte k of a tile
  row, with only bit 4 (left pixel) and bit 0 (right pixel) used. The
  framework ORs the four planes in with shifts (plane 3 first).
TABLES3.INC (resident page, page aligned):
  trace_table[op]: what the trace handler (trace.asm) does with each
  opcode; see tools/tracedef.py.
"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tracedef  # noqa: E402

def db(out, vals):
    for i in range(0, len(vals), 16):
        out.append('\t\tdb ' + ','.join(f'${v:02X}' for v in vals[i:i+16]))

out = ['; generated by tools/gentables.py, do not edit']
out.append('mapattr_table:')
vals = []
for h in range(256):
    a = (h & 1)                 # tile bit 8
    a |= ((h >> 1) & 1) << 3    # H flip -> X mirror
    a |= ((h >> 2) & 1) << 2    # V flip -> Y mirror
    a |= ((h >> 3) & 1) << 4    # sprite palette -> palette offset 1
    vals.append(a)              # bit 4 of h (priority) has no equivalent
db(out, vals)

# SMS 2-bit levels -> Next 3-bit levels: 0, 3, 5, 7 for red, green and
# blue. These are the only blue levels an 8-bit RRRGGGBB colour gives (the
# ninth bit is blue bit 1 OR bit 0), and the fallback colour, NextReg $4A,
# takes only that 8-bit form. One table for all three channels keeps the
# fallback colour equal to the palette colour it stands for, and keeps SMS
# greys grey. tbblue shows 3-bit level v as (v << 5 | v << 2 | v >> 1), so
# the levels are 0, 109, 182, 255; the SMS2 VDP (315-5246) outputs 0, 89,
# 174, 255.
LV = [0, 3, 5, 7]
LVB = LV
hi, lo = [], []
for c in range(64):
    r, g, b = LV[c & 3], LV[(c >> 2) & 3], LVB[(c >> 4) & 3]
    hi.append(r << 5 | g << 2 | b >> 1)
    lo.append(b & 1)
out.append('pal_hi_table:')
db(out, hi)
out.append('pal_lo_table:')
db(out, lo)

out.append('joy_table:')
vals = []
for k in range(64):
    v = 0xFF
    if k & 8: v &= ~0x01   # up
    if k & 4: v &= ~0x02   # down
    if k & 2: v &= ~0x04   # left
    if k & 1: v &= ~0x08   # right
    if k & 16: v &= ~0x10  # button 1 (Kempston fire 1, Mega Drive B)
    if k & 32: v &= ~0x20  # button 2 (Kempston fire 2, Mega Drive C)
    vals.append(v & 0xFF)
db(out, vals)

# The AY volume steps are about 3 dB, the SN76489 steps 2 dB.
out.append('ay_vol_table:')
db(out, [0 if a == 15 else 15 - round(2 * a / 3) for a in range(16)])
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')

out = ['; generated by tools/gentables.py, do not edit']
out.append('conv_tables:')
for k in range(4):
    vals = []
    for b in range(256):
        left = (b >> (7 - 2 * k)) & 1
        right = (b >> (6 - 2 * k)) & 1
        vals.append(left << 4 | right)
    db(out, vals)
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')

out = ['; generated by tools/gentables.py, do not edit']
out.append('trace_table:')
db(out, tracedef.table())
open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
